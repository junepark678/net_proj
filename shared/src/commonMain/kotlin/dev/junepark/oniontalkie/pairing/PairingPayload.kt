package dev.junepark.oniontalkie.pairing

/** Why a pairing payload (or its fields) was rejected. */
enum class PairingError {
    /** The text does not start with `onion-talkie:`. */
    NOT_A_PAIRING_PAYLOAD,

    /** The payload names a protocol version other than 1. */
    UNSUPPORTED_VERSION,

    /** Wrong field count/layout, or the payload is longer than [PairingPayload.MAX_LENGTH]. */
    MALFORMED,

    /** The onion host is not 56 base32 characters with a v3 version byte. */
    INVALID_ONION,

    /** The onion host is well-formed but its rend-spec-v3 checksum does not match. */
    BAD_ONION_CHECKSUM,

    /** The client-auth key is not base32 for exactly 32 bytes. */
    INVALID_KEY,

    /** The display name is blank, too long, or contains control characters. */
    INVALID_DISPLAY_NAME,
}

/** Outcome of [PairingPayload.parse]. */
sealed interface PairingParseResult {
    /** The payload parsed and every field validated. */
    data class Success(val payload: PairingPayload) : PairingParseResult

    /** The payload was rejected for [error]. */
    data class Failure(val error: PairingError) : PairingParseResult
}

/**
 * What a device shows as a QR code to pair: `onion-talkie:v1;<onion>.onion;<x25519 pub base32>;<display name>`.
 *
 * @property onion v3 onion host label, 56 lowercase base32 characters, without `.onion`.
 * @property clientAuthPub the x25519 client-authorization public key (32 bytes); opaque here, generated by #7.
 * @property displayName human-readable name, 1..[MAX_DISPLAY_NAME] characters, no control characters.
 * @throws IllegalArgumentException if any field is invalid; use [parse] for untrusted input.
 */
class PairingPayload(
    val onion: String,
    val clientAuthPub: ByteArray,
    val displayName: String,
) {
    /** Protocol version; only 1 exists. */
    val version: Int get() = VERSION

    init {
        val error = validate(onion, clientAuthPub, displayName)
        require(error == null) { "Invalid pairing payload: $error" }
    }

    /** Encodes to the QR text form. Always at most [MAX_LENGTH] characters. */
    fun encode(): String =
        "$PREFIX$onion.onion;${Base32.encode(clientAuthPub)};$displayName"

    override fun equals(other: Any?): Boolean =
        other is PairingPayload && onion == other.onion &&
            clientAuthPub.contentEquals(other.clientAuthPub) && displayName == other.displayName

    override fun hashCode(): Int =
        (onion.hashCode() * 31 + clientAuthPub.contentHashCode()) * 31 + displayName.hashCode()

    override fun toString(): String = "PairingPayload(onion=$onion, displayName=$displayName)"

    companion object {
        /** The only supported protocol version. */
        const val VERSION = 1

        /** Maximum encoded length in characters. */
        const val MAX_LENGTH = 200

        /** Maximum display-name length; keeps the encoded form within [MAX_LENGTH]. */
        const val MAX_DISPLAY_NAME = 64

        /** Size of an x25519 public key in bytes. */
        const val KEY_SIZE = 32

        private const val SCHEME = "onion-talkie:"
        private const val PREFIX = "${SCHEME}v$VERSION;"
        private const val ONION_SUFFIX = ".onion"

        /** Parses and validates [text]; never throws. */
        fun parse(text: String): PairingParseResult {
            fun fail(error: PairingError) = PairingParseResult.Failure(error)

            if (!text.startsWith(SCHEME)) return fail(PairingError.NOT_A_PAIRING_PAYLOAD)
            if (!text.startsWith(PREFIX)) {
                val versionTag = text.substring(SCHEME.length).substringBefore(';')
                val isVersionTag = versionTag.length > 1 && versionTag[0] == 'v' &&
                    versionTag.drop(1).all { it in '0'..'9' }
                return fail(if (isVersionTag) PairingError.UNSUPPORTED_VERSION else PairingError.MALFORMED)
            }
            if (text.length > MAX_LENGTH) return fail(PairingError.MALFORMED)

            // The display name is last, so it may itself contain ';'.
            val fields = text.substring(PREFIX.length).split(';', limit = 3)
            if (fields.size != 3 || !fields[0].endsWith(ONION_SUFFIX)) return fail(PairingError.MALFORMED)

            val onion = fields[0].removeSuffix(ONION_SUFFIX).lowercase()
            val key = Base32.decode(fields[1]) ?: return fail(PairingError.INVALID_KEY)
            val error = validate(onion, key, fields[2])
            return if (error == null) {
                PairingParseResult.Success(PairingPayload(onion, key, fields[2]))
            } else {
                fail(error)
            }
        }

        private fun validate(onion: String, key: ByteArray, name: String): PairingError? {
            if (onion != onion.lowercase()) return PairingError.INVALID_ONION
            when (OnionAddress.check(onion)) {
                OnionAddress.Check.MALFORMED -> return PairingError.INVALID_ONION
                OnionAddress.Check.BAD_CHECKSUM -> return PairingError.BAD_ONION_CHECKSUM
                OnionAddress.Check.VALID -> Unit
            }
            if (key.size != KEY_SIZE) return PairingError.INVALID_KEY
            if (name.isBlank() || name != name.trim() || name.length > MAX_DISPLAY_NAME ||
                name.any { it.isISOControl() }
            ) {
                return PairingError.INVALID_DISPLAY_NAME
            }
            return null
        }
    }
}
